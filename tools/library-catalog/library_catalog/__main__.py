"""Generate ``library/CATALOG.md`` from the frontmatter of every reference page.

The catalog is the file an agent reads first (vault ``requirements/vault-library.md``
D7): one row per page, then **Wanted**, the prerequisite paths pages lean on
that don't exist yet. Pages are also checked against the page contract (D3);
violations print as warnings, or fail the run with ``--strict``.

    uv run --project tools/library-catalog library-catalog --vault ~/vault
    uv run --project tools/library-catalog library-catalog --vault ~/vault --check --strict
"""

from __future__ import annotations

import argparse
import sys
from collections import defaultdict
from pathlib import Path

import yaml

REQUIRED_KEYS = ("type", "title", "date", "tags", "level", "author", "prereqs", "covers", "sources")
LEVELS = {"foundation", "core", "advanced"}
AUTHORS = {"agent", "chris", "course"}
SKIP_NAMES = {"index.md", "CATALOG.md"}


def read_frontmatter(path: Path) -> dict | None:
    """Return the YAML frontmatter of ``path`` as a dict, or None if it has none."""
    text = path.read_text(encoding="utf-8")
    if not text.startswith("---\n"):
        return None
    end = text.find("\n---", 4)
    if end == -1:
        return None
    try:
        data = yaml.safe_load(text[4:end])
    except yaml.YAMLError as exc:  # a broken page must not take the catalog down silently
        raise SystemExit(f"{path}: frontmatter does not parse: {exc}") from exc
    return data if isinstance(data, dict) else None


def contract_problems(rel: str, fm: dict) -> list[str]:
    """List the page-contract violations in one page's frontmatter."""
    problems = []
    for key in REQUIRED_KEYS:
        if key not in fm or fm[key] in (None, ""):
            problems.append(f"{rel}: missing `{key}`")
        elif fm[key] == [] and key != "prereqs":  # `prereqs: []` is a foundation page
            problems.append(f"{rel}: missing `{key}`")
    if fm.get("level") not in LEVELS:
        problems.append(f"{rel}: `level` must be one of {sorted(LEVELS)}, got {fm.get('level')!r}")
    if fm.get("author") not in AUTHORS:
        problems.append(f"{rel}: `author` must be one of {sorted(AUTHORS)}, got {fm.get('author')!r}")
    tags = fm.get("tags") or []
    if "reference" not in tags:
        problems.append(f"{rel}: `tags` must include `reference`")
    covers = fm.get("covers") or []
    if not 5 <= len(covers) <= 8:
        problems.append(f"{rel}: `covers` has {len(covers)} questions, contract says 5–8")
    for i, src in enumerate(fm.get("sources") or []):
        if not isinstance(src, dict) or not src.get("title") or not src.get("fetched"):
            problems.append(f"{rel}: source {i + 1} needs `title` and `fetched`")
    return problems


def collect(library: Path) -> tuple[list[dict], list[str]]:
    """Walk ``library`` and return (pages, contract problems)."""
    pages, problems = [], []
    for path in sorted(library.rglob("*.md")):
        if path.name in SKIP_NAMES or path.name.startswith("_"):
            continue
        fm = read_frontmatter(path)
        if not fm or fm.get("type") != "reference":
            continue
        rel = path.relative_to(library).as_posix()
        problems.extend(contract_problems(rel, fm))
        covers = fm.get("covers") or []
        pages.append(
            {
                "path": rel,
                "title": str(fm.get("title") or path.stem),
                "level": str(fm.get("level") or ""),
                "author": str(fm.get("author") or ""),
                "tags": [t for t in (fm.get("tags") or []) if t != "reference"],
                "first": str(covers[0]) if covers else "",
                "prereqs": [str(p) for p in (fm.get("prereqs") or [])],
            }
        )
    return pages, problems


def contract_line(root: Path) -> str:
    """The header's pointer to the page contract, for whichever root this is.

    The vault carries the contract at ``requirements/vault-library.md``; a
    meta-repo vendored from the public mirror carries the tool and its
    README instead (roadmap/16 D7); anything else gets the rule in words.
    Checked in that order, relative to ``library/`` where CATALOG.md lives.
    """
    for rel, label in (
        ("requirements/vault-library.md", "D7"),
        ("tools/library-catalog/README.md", "page contract"),
    ):
        if (root / rel).is_file():
            return f"[{rel}](../{rel}) {label}."
    return "every page's frontmatter is the contract; see the tool's README."


def render(pages: list[dict], contract: str) -> str:
    """Render the catalog markdown."""
    existing = {p["path"] for p in pages}
    wanted: dict[str, list[str]] = defaultdict(list)
    for page in pages:
        for pre in page["prereqs"]:
            if pre not in existing:
                wanted[pre].append(page["path"])

    out = [
        "# Library catalog",
        "",
        "Generated by `tools/library-catalog` (agentic_optimization_research)",
        "from every reference page's frontmatter. Regenerate in every PR that",
        "adds or changes a page; hand edits are overwritten. Contract:",
        contract,
        "",
        f"{len(pages)} page{'s' if len(pages) != 1 else ''}. Read this file first, then open the page;",
        "open an index only if this didn't settle it.",
        "",
        "## Pages",
        "",
        "| Path | Title | Level | Author | Tags | First question |",
        "|---|---|---|---|---|---|",
    ]
    for page in pages:
        tags = ", ".join(page["tags"])
        out.append(
            f"| [{page['path']}]({page['path']}) | {page['title']} | {page['level']} | "
            f"{page['author']} | {tags} | {page['first']} |"
        )
    out += [
        "",
        "## Wanted",
        "",
        "Prerequisites that existing pages lean on and that don't exist yet:",
        "the library's own queue, most-wanted first.",
        "",
    ]
    if wanted:
        out += ["| Wanted page | Wanted by |", "|---|---|"]
        for pre, by in sorted(wanted.items(), key=lambda kv: (-len(kv[1]), kv[0])):
            links = ", ".join(f"[{b}]({b})" for b in by)
            out.append(f"| `{pre}` | {links} |")
    else:
        out.append("*(nothing — every prerequisite exists)*")
    out.append("")
    return "\n".join(out)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="library-catalog", description=__doc__.split("\n\n")[0])
    parser.add_argument("--vault", default=str(Path.home() / "vault"), help="the root that holds library/ (default ~/vault; a meta-repo works too)")
    parser.add_argument("--check", action="store_true", help="exit 1 if CATALOG.md differs from the generated text; write nothing")
    parser.add_argument("--strict", action="store_true", help="exit 1 on any page-contract violation")
    args = parser.parse_args(argv)

    library = Path(args.vault).expanduser() / "library"
    if not library.is_dir():
        print(f"no library/ under {args.vault}", file=sys.stderr)
        return 2

    pages, problems = collect(library)
    for problem in problems:
        print(f"warning: {problem}", file=sys.stderr)

    text = render(pages, contract_line(Path(args.vault).expanduser()))
    target = library / "CATALOG.md"
    status = 0
    if args.check:
        current = target.read_text(encoding="utf-8") if target.exists() else ""
        if current != text:
            print(f"{target} is out of date; run without --check to regenerate", file=sys.stderr)
            status = 1
        else:
            print(f"ok: {target} matches {len(pages)} pages")
    else:
        target.write_text(text, encoding="utf-8")
        print(f"wrote {target}: {len(pages)} pages")

    if problems and args.strict:
        print(f"{len(problems)} contract violation(s)", file=sys.stderr)
        status = 1
    return status


if __name__ == "__main__":
    sys.exit(main())
